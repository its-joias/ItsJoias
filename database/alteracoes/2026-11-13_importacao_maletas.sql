-- =====================================================================
-- ITS Joias — importação de maletas por PDF
--
-- 1. maletas.data_acerto: data combinada para o acerto com o fornecedor.
--    É por ela que a Leide identifica a maleta (a do mês passado é a "antiga").
-- 2. fornecedores.cnpj: identifica o fornecedor no PDF mesmo que o nome venha
--    escrito diferente (ex.: "It Store Semijoias ltda." / "IT STORE SEMIJOIAS LTDA").
-- 3. importacoes_maleta: histórico de cada importação (arquivo, impressão
--    digital do arquivo, quem importou, quando, quantas peças).
-- 4. A categoria de um modelo não pode mais mudar depois que ele tem peças:
--    a troca de categoria troca o código (C0001 -> K0001) e a etiqueta já
--    impressa na peça deixaria de bater com o sistema.
-- 5. Palavras-chave "bri" e "col", abreviações usadas nas descrições da
--    It Store ("BRI SJ OURO...", "COL SJ PRATA...").
--
-- Não apaga nem altera nenhum dado existente.
-- COMO RODAR: pgAdmin > Query Tool > executar o ARQUIVO INTEIRO (F5). Uma vez só.
-- =====================================================================

BEGIN;

-- 1 e 2 -----------------------------------------------------------------
ALTER TABLE maletas      ADD COLUMN data_acerto DATE;
ALTER TABLE fornecedores ADD COLUMN cnpj VARCHAR(18);
ALTER TABLE fornecedores ADD CONSTRAINT ck_fornecedores_cnpj
    CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{2}\.[0-9]{3}\.[0-9]{3}/[0-9]{4}-[0-9]{2}$');
CREATE UNIQUE INDEX uq_fornecedores_cnpj ON fornecedores (cnpj) WHERE cnpj IS NOT NULL;

-- 3 ---------------------------------------------------------------------
CREATE TABLE importacoes_maleta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maleta_id          BIGINT       NOT NULL REFERENCES maletas      (id) ON DELETE RESTRICT,
    fornecedor_id      BIGINT       NOT NULL REFERENCES fornecedores (id) ON DELETE RESTRICT,
    usuario_id         BIGINT       NOT NULL REFERENCES usuarios     (id) ON DELETE RESTRICT,
    arquivo_nome       VARCHAR(255) NOT NULL,
    arquivo_hash       CHAR(64)     NOT NULL,          -- SHA-256 do arquivo: o mesmo PDF tem sempre o mesmo valor
    arquivo_tamanho    INTEGER      NOT NULL,
    metodo_leitura     VARCHAR(10)  NOT NULL,          -- TEXTO (PDF digital) ou OCR (PDF escaneado/foto)
    pedido_fornecedor  VARCHAR(40),                    -- nº do pedido/termo no documento
    linhas_lidas       INTEGER      NOT NULL,
    linhas_ignoradas   INTEGER      NOT NULL,
    modelos_novos      INTEGER      NOT NULL,
    pecas_importadas   INTEGER      NOT NULL,
    valor_total        NUMERIC(12,2) NOT NULL,
    reimportacao_confirmada BOOLEAN NOT NULL DEFAULT FALSE,  -- o mesmo arquivo já tinha sido importado e a pessoa confirmou
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_importacoes_metodo CHECK (metodo_leitura IN ('TEXTO', 'OCR')),
    CONSTRAINT ck_importacoes_hash   CHECK (arquivo_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_importacoes_numeros CHECK (linhas_lidas >= 0 AND linhas_ignoradas >= 0
                                             AND modelos_novos >= 0 AND pecas_importadas > 0 AND valor_total >= 0)
);
CREATE INDEX ix_importacoes_hash       ON importacoes_maleta (arquivo_hash);
CREATE INDEX ix_importacoes_maleta     ON importacoes_maleta (maleta_id);
CREATE INDEX ix_importacoes_fornecedor ON importacoes_maleta (fornecedor_id);
CREATE INDEX ix_importacoes_usuario    ON importacoes_maleta (usuario_id);

-- histórico não se edita nem se apaga
CREATE TRIGGER trg_importacoes_imutavel BEFORE UPDATE OR DELETE ON importacoes_maleta
    FOR EACH ROW EXECUTE FUNCTION fn_bloquear_alteracao();

-- 4 ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_produtos_codigo() RETURNS trigger LANGUAGE plpgsql
    SET search_path = public, pg_temp AS $$
DECLARE
    v_prefixo  VARCHAR;
    v_numero   INTEGER;
BEGIN
    -- a etiqueta impressa (C0001-01) não pode deixar de valer
    IF TG_OP = 'UPDATE' AND NEW.categoria_id IS DISTINCT FROM OLD.categoria_id
       AND EXISTS (SELECT 1 FROM pecas WHERE produto_id = OLD.id) THEN
        RAISE EXCEPTION 'O modelo % já tem peças com etiqueta; a categoria não pode mudar (as etiquetas impressas deixariam de valer).', OLD.codigo;
    END IF;

    IF TG_OP = 'INSERT' OR NEW.categoria_id IS DISTINCT FROM OLD.categoria_id THEN
        -- o UPDATE trava a linha da categoria: dois cadastros simultâneos nunca pegam o mesmo número
        UPDATE categorias
           SET proximo_numero = proximo_numero + 1
         WHERE id = NEW.categoria_id
        RETURNING prefixo, proximo_numero - 1 INTO v_prefixo, v_numero;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Categoria % não existe.', NEW.categoria_id;
        END IF;

        IF TG_OP = 'UPDATE' THEN
            INSERT INTO produto_codigos_historico (produto_id, codigo) VALUES (OLD.id, OLD.codigo);
        END IF;

        -- C0001 ... C9999, C10000 (nunca corta dígitos)
        NEW.codigo := v_prefixo || lpad(v_numero::text, greatest(4, length(v_numero::text)), '0');
    ELSIF NEW.codigo IS DISTINCT FROM OLD.codigo THEN
        RAISE EXCEPTION 'O código do produto é gerado pelo sistema; para mudar, troque a categoria.';
    END IF;
    RETURN NEW;
END $$;

-- 5 ---------------------------------------------------------------------
INSERT INTO categoria_palavras_chave (categoria_id, termo, prioridade)
SELECT c.id, t.termo, t.prioridade
FROM (VALUES ('B', 'bri', 1), ('C', 'col', 1)) AS t (prefixo, termo, prioridade)
JOIN categorias c ON c.prefixo = t.prefixo
ON CONFLICT (termo) DO NOTHING;

-- Supabase: a tabela nova também fica fechada para a API pública (só o back acessa)
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        ALTER TABLE importacoes_maleta ENABLE ROW LEVEL SECURITY;
        REVOKE ALL ON importacoes_maleta FROM anon, authenticated;
    END IF;
END $$;

COMMIT;
